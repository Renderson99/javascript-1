//Com for
for (let i = 0; i <= 5; i++) {
    console.log(`Com for: ${i}`)
}

//Com while
let cont = 0

while (cont <= 5) {
    console.log(`Com while: ${cont}`)
    cont = cont + 1
}

//Com for of
let frutas = ["Manga", "Uva", "Maçã", "Pera", "Caju"]

for (const fruta of frutas) {
    console.log(`Com for of: ${fruta}`)
}
